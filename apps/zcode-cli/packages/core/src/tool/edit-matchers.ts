/**
 * Нормализация переводов строк для текстов правки.
 *
 * Причина, по которой модуль сведён к одной функции: нечёткий каскад сопоставления
 * `old_string` (6 стратегий + block-anchor) был заменён `MultiTierDiffEngine`
 * (Инкремент 4.2), который стал единственным путём правки файлов. Оставшийся каскад
 * не вызывался ниоткуда, поэтому удалён, а не законсервирован.
 *
 * `Edit` и `ApplyPatch` по-прежнему обязаны приводить CRLF к LF до передачи текста
 * в движок: иначе `old_string` из модели не совпадёт с содержимым файла на Windows.
 */
export function normalizeLineEndings(content: string): string {
  return content.replaceAll("\r\n", "\n");
}
